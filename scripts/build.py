#!/usr/bin/env python3
"""Generate one HTML file per page from src/index.html.

Why: social apps (Facebook, LINE) and search engines read a page's <title>,
description and share preview straight from the HTML, without running
JavaScript. With a single index.html every shared link showed the home page.
Each generated file now carries its own title/meta/canonical, its own <h1>,
and only its own section.

Run after every edit to src/index.html or to ROUTES in assets/js/app.js:

    python scripts/build.py

Then commit the generated files with the source. Vercel serves them as-is
(no build step on Vercel).
"""
import html
import json
import re
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src" / "index.html"
APP_JS = ROOT / "assets" / "js" / "app.js"
VERCEL = ROOT / "vercel.json"
SITEMAP = ROOT / "sitemap.xml"

# Pages left out of sitemap.xml (still published).
NOT_IN_SITEMAP = {"privacy", "gallery"}
# Published but kept out of Google (<meta name="robots" content="noindex">).
# gallery: only placeholder tiles until real project photos are added —
# remove it from both sets (and put it back in the nav) once photos are in.
NOINDEX = {"gallery"}
PRIORITY = {"home": "1.0", "products": "0.9", "services": "0.9", "contact": "0.9", "faq": "0.8",
            "service-area": "0.8", "area-sriracha": "0.9", "area-chonburi": "0.9", "area-bangkok": "0.9"}

BANNER = ("<!-- GENERATED by scripts/build.py from src/index.html — do not edit this file.\n"
          "     Edit src/index.html, then run: python scripts/build.py -->\n")


def read_routes():
    """Read ROUTES (name, path, title, desc) from app.js — the one place they live."""
    js = APP_JS.read_text(encoding="utf-8")
    consts = {}
    for name in ("SITE_NAME", "SITE_URL", "DEFAULT_DESC"):
        m = re.search(r"var %s\s*=\s*'([^']*)';" % name, js)
        consts[name] = m.group(1)

    def evaluate(expr):
        out = []
        for part in expr.split("+"):
            part = part.strip()
            if part.startswith("'") and part.endswith("'"):
                out.append(part[1:-1])
            elif part in consts:
                out.append(consts[part])
            else:
                raise ValueError("Cannot read ROUTES value: %r" % expr)
        return "".join(out)

    block = js[js.index("var ROUTES = {"):js.index("};", js.index("var ROUTES = {"))]
    routes = []
    for m in re.finditer(
            r"^\s*'?([\w-]+)'?\s*:\s*\{\s*path:\s*'([^']*)',\s*title:\s*(.+?),\s*desc:\s*(.+?)\s*\},?\s*$",
            block, re.M):
        routes.append({"name": m.group(1), "path": m.group(2),
                       "title": evaluate(m.group(3)), "desc": evaluate(m.group(4))})
    if not routes:
        raise SystemExit("No ROUTES found in app.js")
    return consts["SITE_URL"], routes


def split_sections(doc):
    """Return (before, {page: block}, after) for the <main> content."""
    start = doc.index('<main id="main">') + len('<main id="main">')
    end = doc.index("</main>")
    body = doc[start:end]
    blocks = re.findall(r"\n  <!-- ══[\s\S]*?-->\n  <section[\s\S]*?\n  </section>\n", body)
    if len(blocks) != body.count("data-page="):
        raise SystemExit("src/index.html: every <section data-page> inside <main> must be "
                         "preceded by its <!-- ══ … --> comment and end with '  </section>'.")
    by_page = {}
    for b in blocks:
        pages = re.findall(r'data-page="([^"]+)"', b)
        if len(pages) != 1:
            raise SystemExit("Expected one data-page per section, got %r" % pages)
        by_page[pages[0]] = b
    return doc[:start], by_page, doc[end:]


def set_attr(doc, pattern, value):
    new, n = re.subn(pattern, lambda m: m.group(1) + html.escape(value, quote=True) + m.group(2), doc, count=1)
    if n != 1:
        raise SystemExit("Pattern not found in <head>: " + pattern)
    return new


def strip_tags(fragment):
    text = re.sub(r"<[^>]+>", "", fragment)
    return re.sub(r"\s+", " ", html.unescape(text)).strip()


def faq_jsonld(section):
    items = []
    for m in re.finditer(r'<details class="faq-item">\s*<summary>([\s\S]*?)</summary>\s*'
                         r'<div class="faq-item__answer">([\s\S]*?)</div>\s*</details>', section):
        items.append({"@type": "Question", "name": strip_tags(m.group(1)),
                      "acceptedAnswer": {"@type": "Answer", "text": strip_tags(m.group(2))}})
    data = {"@context": "https://schema.org", "@type": "FAQPage", "mainEntity": items}
    return ('<script type="application/ld+json">\n'
            + json.dumps(data, ensure_ascii=False, indent=2) + "\n</script>\n")


def out_file(path):
    return ROOT / "index.html" if path == "/" else ROOT / path.strip("/") / "index.html"


def main():
    site_url, routes = read_routes()
    src = SRC.read_text(encoding="utf-8")
    before, sections, after = split_sections(src)

    missing = [r["name"] for r in routes if r["name"] not in sections]
    extra = [p for p in sections if p not in {r["name"] for r in routes}]
    if missing or extra:
        raise SystemExit("ROUTES and sections differ — missing sections: %s, sections without a route: %s"
                         % (missing, extra))

    for r in routes:
        url = site_url + r["path"]
        head = before
        head = re.sub(r"<title>[\s\S]*?</title>", lambda m: "<title>%s</title>" % html.escape(r["title"], quote=False), head, count=1)
        head = set_attr(head, r'(<meta name="description" content=")[^"]*(")', r["desc"])
        head = set_attr(head, r'(<link rel="canonical" href=")[^"]*(")', url)
        head = set_attr(head, r'(<meta property="og:url" content=")[^"]*(")', url)
        head = set_attr(head, r'(<meta property="og:title" content=")[^"]*(")', r["title"])
        head = set_attr(head, r'(<meta property="og:description" content=")[^"]*(")', r["desc"])
        if r["name"].startswith("article-"):
            head = head.replace('<meta property="og:type" content="website">',
                                '<meta property="og:type" content="article">', 1)
        if r["name"] in NOINDEX:
            head = head.replace("</head>", '<meta name="robots" content="noindex, follow">\n</head>', 1)
        if r["name"] == "faq":
            head = head.replace("</head>", faq_jsonld(sections["faq"]) + "</head>", 1)
        head = re.sub(r"^(<!doctype html>\n)", lambda m: m.group(1) + BANNER, head, count=1, flags=re.I)

        doc = head + sections[r["name"]] + "\n" + after
        target = out_file(r["path"])
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(doc, encoding="utf-8")
        print("wrote", target.relative_to(ROOT))

    # vercel.json: clean URL -> generated file (keeps every other setting).
    cfg = json.loads(VERCEL.read_text(encoding="utf-8"))
    cfg["rewrites"] = [{"source": r["path"], "destination": "/" + out_file(r["path"]).relative_to(ROOT).as_posix()}
                       for r in routes if r["path"] != "/"]
    VERCEL.write_text(json.dumps(cfg, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    # sitemap.xml
    today = date.today().isoformat()
    urls = "".join(
        "  <url>\n    <loc>%s%s</loc>\n    <lastmod>%s</lastmod>\n    <priority>%s</priority>\n  </url>\n"
        % (site_url, r["path"], today, PRIORITY.get(r["name"], "0.7"))
        for r in routes if r["name"] not in NOT_IN_SITEMAP)
    SITEMAP.write_text('<?xml version="1.0" encoding="UTF-8"?>\n'
                       '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
                       + urls + "</urlset>\n", encoding="utf-8")
    print("updated vercel.json, sitemap.xml")


if __name__ == "__main__":
    main()
